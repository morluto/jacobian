class ElementCyclesRequest(_ActionRequest):
    """Request the cycle decomposition of one group element.

    ``element`` is the index (0-based) into the enumerated group order of the
    action; the identity element is always at index 0.
    """

    element: int = Field(ge=0)


class ElementCyclesResult(StrictModel):
    """Source-bound cycle decomposition of one group element.

    Each ``cycle`` is a tuple of 0-based position indices in the domain.  The
    canonical representative starts with the smallest index and cycles are
    ordered by their smallest element.  ``cycle_lengths`` is the sorted list
    of cycle lengths; ``cycle_type`` is the integer partition of ``|X|`` given
    by the cycle lengths in non-increasing order.  ``fixed_points`` lists the
    domain indices fixed by the element.
    The relation between ``permutation`` and the cycle rows, and all derived
    profile fields, are claims established by the producing operation.  They
    are checked by ``verify_element_cycles`` when a consumer relies on them;
    ordinary deserialization only checks their bounded representation.
    """

    action: FinitePermutationAction
    element: int
    permutation: tuple[DomainPosition, ...] = Field(max_length=MAX_DOMAIN_SIZE)
    cycles: tuple[tuple[DomainPosition, ...], ...] = Field(
        max_length=MAX_DOMAIN_SIZE
    )
    cycle_lengths: tuple[int, ...] = Field(max_length=MAX_DOMAIN_SIZE)
    cycle_type: tuple[int, ...] = Field(max_length=MAX_DOMAIN_SIZE)
    fixed_points: tuple[DomainPosition, ...] = Field(max_length=MAX_DOMAIN_SIZE)
    fixed_point_count: int = Field(ge=0, le=MAX_DOMAIN_SIZE)
    support: tuple[DomainPosition, ...] = Field(max_length=MAX_DOMAIN_SIZE)

    @model_validator(mode="after")
    def bind_element_cycles(self) -> Self:
        n = len(self.action.domain)
        if self.element < 0:
            raise _validation_error("element_negative", "element must be non-negative")
        if len(self.permutation) != n or sorted(self.permutation) != list(range(n)):
            raise _validation_error(
                "permutation_not_permutation",
                "permutation must be a permutation of the action domain",
            )
        if len(self.cycles) > n or any(
            not cycle or len(cycle) > n or any(not 0 <= index < n for index in cycle)
            for cycle in self.cycles
        ):
            raise _validation_error(
                "cycle_shape", "cycle rows must be bounded nonempty domain indices"
            )
        for positions in (self.fixed_points, self.support):
            if tuple(sorted(set(positions))) != positions or any(
                not 0 <= index < n for index in positions
            ):
                raise _validation_error(
                    "profile_axis", "profile positions must be canonical domain subsets"
                )
        if not 0 <= self.fixed_point_count <= n:
            raise _validation_error(
                "profile_bound", "fixed-point count must be bounded by the domain"
            )
        for lengths in (self.cycle_lengths, self.cycle_type):
            if len(lengths) > n or any(not 1 <= length <= n for length in lengths):
                raise _validation_error(
                    "cycle_length_bound", "cycle lengths must fit the domain"
                )
        return self

    @classmethod
    def _from_kernel(
        cls,
        action: FinitePermutationAction,
        element: int,
        permutation: tuple[int, ...],
        cycles: tuple[tuple[int, ...], ...],
        cycle_lengths: tuple[int, ...],
        cycle_type: tuple[int, ...],
        fixed_points: tuple[int, ...],
        support: tuple[int, ...],
    ) -> Self:
        return cls.model_construct(
            action=action,
            element=element,
            permutation=permutation,
            cycles=cycles,
            cycle_lengths=cycle_lengths,
            cycle_type=cycle_type,
            fixed_points=fixed_points,
            fixed_point_count=len(fixed_points),
            support=support,
        )


