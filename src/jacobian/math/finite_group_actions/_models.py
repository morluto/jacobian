class ElementCyclesRequest(_ActionRequest):
    """Request the cycle decomposition of one group element.

    ``element`` is the index (0-based) into the enumerated group order of the
    action; the identity element is always at index 0.
    """

    element: int = Field(ge=0)


class ElementCyclesResult(StrictModel):
    """Cycle decomposition of one group element acting on the domain.

    Each ``cycle`` is a tuple of 0-based position indices in the domain.  The
    canonical representative starts with the smallest index and cycles are
    ordered by their smallest element.  ``cycle_lengths`` is the sorted list
    of cycle lengths; ``cycle_type`` is the integer partition of ``|X|`` given
    by the cycle lengths in non-increasing order.  ``fixed_points`` lists the
    domain indices fixed by the element.
    """

    action: FinitePermutationAction
    element: int
    permutation: tuple[int, ...]
    cycles: tuple[tuple[int, ...], ...]
    cycle_lengths: tuple[int, ...]
    cycle_type: tuple[int, ...]
    fixed_points: tuple[int, ...]
    fixed_point_count: int
    support: tuple[int, ...]

    @model_validator(mode="after")
    def bind_element_cycles(self) -> Self:
        from jacobian.math.finite_group_actions._operations import _element_cycles_data

        permutation, cycles, lengths, cycle_type, fixed, support = _element_cycles_data(
            self.action, self.element
        )
        if self.permutation != permutation:
            raise ValueError("permutation must be the exact enumerated group element")
        if self.cycles != cycles:
            raise ValueError("cycles must be the exact cycle decomposition")
        if self.cycle_lengths != lengths:
            raise ValueError("cycle_lengths must match the computed cycle lengths")
        if self.cycle_type != cycle_type:
            raise ValueError("cycle_type must be the integer partition of |X|")
        if self.fixed_points != fixed:
            raise ValueError("fixed_points must be the exact fixed-point set")
        if self.fixed_point_count != len(fixed):
            raise ValueError("fixed_point_count must equal len(fixed_points)")
        if self.support != support:
            raise ValueError("support must be the exact support set")
        return self


