class BurnsideCountRequest(_ActionRequest):
    """Request the number of orbits under the action via Burnside's lemma."""


class BurnsideCountResult(StrictModel):
    """The number of point-orbits under the action.

    ``orbit_count`` is the exact integer ``|G\\X| = (1/|G|) sum_g |Fix(g)|``.
    ``fixed_point_contributions`` lists, for each group element, its
    ``|Fix(g)|`` value in enumerated order.  ``group_order`` is ``|G|``.
    """

    action: FinitePermutationAction
    group_order: int
    fixed_point_sum: int
    orbit_count: int
    fixed_point_contributions: tuple[int, ...]

    @model_validator(mode="after")
    def bind_burnside(self) -> Self:
        from jacobian.math.finite_group_actions._operations import _burnside_data

        order, contributions, orbit_count = _burnside_data(self.action)
        if self.group_order != order:
            raise ValueError("group_order must equal the exact |G|")
        if self.fixed_point_contributions != contributions:
            raise ValueError(
                "fixed_point_contributions must be the exact |Fix(g)| table"
            )
        if self.fixed_point_sum != sum(contributions):
            raise ValueError("fixed_point_sum must equal the sum of contributions")
        if self.orbit_count != orbit_count:
            raise ValueError("orbit_count must equal the exact Burnside orbit count")
        return self


