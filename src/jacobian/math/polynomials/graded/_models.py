def _t_minus_one_divides(h_coefficients: dict[int, int]) -> bool:
    """Whether ``h(t)`` is divisible by ``t - 1`` (equivalently ``h(1) = 0``)."""

    return sum(h_coefficients.values()) == 0


def _series_coefficient(
    h_coefficients: dict[int, int], denominator_exponent: int, degree: int
) -> int:
    """Coefficient of ``t^degree`` in ``h(t) / (1-t)^denominator_exponent``."""

    if denominator_exponent == 0:
        return h_coefficients.get(degree, 0)
    return sum(
        coefficient
        * comb(
            degree - shift + denominator_exponent - 1,
            denominator_exponent - 1,
        )
        for shift, coefficient in h_coefficients.items()
        if shift <= degree
    )


def _one_minus_t_power(degree: int) -> SparseRationalPolynomial:
    """Return ``(1-t)^degree`` as a sparse polynomial."""

    terms = tuple(
        RationalPolynomialTerm(
            coefficient=CanonicalRational(
                num=comb(degree, index) * ((-1) ** index), den=1
            ),
            exponents=(index,),
        )
        for index in range(degree, -1, -1)
        if comb(degree, index) != 0
    )
    return SparseRationalPolynomial(terms=terms)


def _sparse_t_multiply(
    left: SparseRationalPolynomial, right: SparseRationalPolynomial
) -> SparseRationalPolynomial:
    """Multiply two univariate sparse rational polynomials exactly."""

    from fractions import Fraction

    coefficients: dict[int, Fraction] = {}
    for left_term in left.terms:
        for right_term in right.terms:
            exponent = left_term.exponents[0] + right_term.exponents[0]
            product = Fraction(
                left_term.coefficient.num * right_term.coefficient.num,
                left_term.coefficient.den * right_term.coefficient.den,
            )
            coefficients[exponent] = coefficients.get(exponent, Fraction()) + product
    terms = tuple(
        RationalPolynomialTerm(
            coefficient=CanonicalRational.from_fraction(value),
            exponents=(exponent,),
        )
        for exponent, value in sorted(coefficients.items(), reverse=True)
        if value != 0
    )
    return SparseRationalPolynomial(terms=terms)


def _sparse_t_negate(
    polynomial: SparseRationalPolynomial,
) -> SparseRationalPolynomial:
    return SparseRationalPolynomial(
        terms=tuple(
            RationalPolynomialTerm(
                coefficient=CanonicalRational(
                    num=-term.coefficient.num, den=term.coefficient.den
                ),
                exponents=term.exponents,
            )
            for term in polynomial.terms
        )
    )


def _monic_t_minus_one_power(degree: int) -> SparseRationalPolynomial:
    terms = tuple(
        RationalPolynomialTerm(
            coefficient=CanonicalRational(
                num=comb(degree, index) * ((-1) ** (degree - index)), den=1
            ),
            exponents=(index,),
        )
        for index in range(degree, -1, -1)
        if comb(degree, index) != 0
    )
    return SparseRationalPolynomial(terms=terms)


class HilbertSeriesResult(StrictModel):
    """A bounded Hilbert series with both canonical and graded numerator axes.

    ``reduced_numerator`` is the numerator owned by the canonical rational
    function carrier, whose denominator is monic.  ``h_numerator`` is the
    sign-corrected numerator in the mathematical convention
    ``H(t) = h(t)/(1-t)^d``; the two differ when ``d`` is odd.
    """

    ideal: RationalPolynomialIdeal
    initial_ideal: RationalPolynomialIdeal
    monomial_order: Literal["lex", "grlex", "grevlex"]
    ambient_numerator: RationalPolynomial
    ambient_denominator_exponent: StrictInt = Field(ge=0)
    series: RationalFunction
    reduced_numerator: RationalPolynomial
    h_numerator: RationalPolynomial
    denominator_exponent: StrictInt = Field(ge=0, le=MAX_RATIONAL_FUNCTION_EXPONENT)
    prefix: tuple[NonnegativeHilbertCount, ...] = Field(
        min_length=1, max_length=MAX_HILBERT_PREFIX + 1
    )

    @model_validator(mode="after")
    def require_source_and_axes(self) -> Self:
        if self.ideal.variables != self.initial_ideal.variables:
            raise ValueError("Hilbert-series values must share the source ring")
        if self.ambient_denominator_exponent != len(self.ideal.variables):
            raise ValueError(
                "ambient denominator exponent must equal the source-ring dimension"
            )
        if self.denominator_exponent > len(self.ideal.variables):
            raise ValueError(
                "Hilbert-series dimension cannot exceed the source-ring dimension"
            )
        if self.ambient_numerator.variables != ("t",):
            raise ValueError("Hilbert-series numerators use the t axis")
        if self.series.variables != ("t",):
            raise ValueError("Hilbert-series values use the t axis")
        if self.series.numerator != self.reduced_numerator.polynomial:
            raise ValueError("reduced numerator must match the rational-series carrier")
        if self.reduced_numerator.variables != ("t",) or self.h_numerator.variables != (
            "t",
        ):
            raise ValueError("Hilbert-series numerators use the t axis")
        if self.denominator_exponent > MAX_RATIONAL_FUNCTION_EXPONENT:
            raise ValueError(
                "Hilbert-series denominator exponent exceeds the rational-function envelope"
            )
        expected_denominator = _monic_t_minus_one_power(self.denominator_exponent)
        if self.series.denominator != expected_denominator:
            raise ValueError(
                "Hilbert-series denominator must be the monic (t-1)^d form"
            )
        sign = -1 if self.denominator_exponent % 2 else 1
        expected_h = tuple(
            RationalPolynomialTerm(
                coefficient=CanonicalRational(
                    num=sign * term.coefficient.num, den=term.coefficient.den
                ),
                exponents=term.exponents,
            )
            for term in self.reduced_numerator.polynomial.terms
        )
        if self.h_numerator.polynomial.terms != expected_h:
            raise ValueError("h-numerator must match the (1-t)^d sign convention")
        self._require_reduced_series()
        # The ambient presentation ``ambient_numerator / (1-t)^n`` must reduce to
        # the reported series. Clearing denominators gives the exact polynomial
        # identity ``ambient_numerator = (-1)^d reduced_numerator (1-t)^(n-d)``,
        # checked by bounded sparse multiplication rather than symbolic
        # cancellation so result construction does not replay the kernel.
        exponent = self.ambient_denominator_exponent - self.denominator_exponent
        if exponent < 0:
            raise ValueError(
                "ambient denominator exponent cannot be below the series dimension"
            )
        expected = _sparse_t_multiply(
            self.reduced_numerator.polynomial, _one_minus_t_power(exponent)
        )
        if self.denominator_exponent % 2:
            expected = _sparse_t_negate(expected)
        if self.ambient_numerator.polynomial.terms != expected.terms:
            raise ValueError(
                "ambient numerator must reduce to the reported Hilbert series"
            )
        return self

    def _require_reduced_series(self) -> None:
        """Reject a common (t-1) factor and bind the prefix to the numerator."""

        h_coefficients: dict[int, int] = {}
        for term in self.h_numerator.polynomial.terms:
            coefficient = term.coefficient.as_fraction()
            if coefficient.denominator != 1:
                raise ValueError("h-numerator coefficients must be integers")
            h_coefficients[term.exponents[0]] = coefficient.numerator
        if self.denominator_exponent >= 1 and _t_minus_one_divides(h_coefficients):
            raise ValueError(
                "reduced numerator must not share a (t-1) factor with the denominator"
            )
        expected_prefix = tuple(
            _series_coefficient(h_coefficients, self.denominator_exponent, degree)
            for degree in range(len(self.prefix))
        )
        if tuple(self.prefix) != expected_prefix:
            raise ValueError("prefix must equal the h-numerator series coefficients")
        # The ambient presentation ``ambient_numerator / (1-t)^n`` must reduce to
        # the reported series. Clearing denominators gives the exact polynomial
        # identity ``ambient_numerator = (-1)^d reduced_numerator (1-t)^(n-d)``,
        # checked by bounded sparse multiplication rather than symbolic
        # cancellation so result construction does not replay the kernel.
        exponent = self.ambient_denominator_exponent - self.denominator_exponent
        if exponent < 0:
            raise ValueError(
                "ambient denominator exponent cannot be below the series dimension"
            )
        expected = _sparse_t_multiply(
            self.reduced_numerator.polynomial, _one_minus_t_power(exponent)
        )
        if self.denominator_exponent % 2:
            expected = _sparse_t_negate(expected)
        if self.ambient_numerator.polynomial.terms != expected.terms:
            raise ValueError(
                "ambient numerator must reduce to the reported Hilbert series"
            )


class HilbertPolynomialResult(StrictModel):
    ideal: RationalPolynomialIdeal
    initial_ideal: RationalPolynomialIdeal
    monomial_order: Literal["lex", "grlex", "grevlex"]
    dimension: StrictInt = Field(ge=0)
    polynomial: RationalPolynomial
    stabilization_degree: StrictInt = Field(ge=0)

    @model_validator(mode="after")
    def require_source_and_axis(self) -> Self:
        if self.ideal.variables != self.initial_ideal.variables:
            raise ValueError("Hilbert-polynomial values must share the source ring")
        if self.dimension > len(self.ideal.variables):
            raise ValueError(
                "Hilbert-polynomial dimension cannot exceed the source-ring dimension"
            )
        if self.polynomial.variables != ("m",):
            raise ValueError("Hilbert polynomial uses the m axis")
        return self


