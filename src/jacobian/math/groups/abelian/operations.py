"""Exact native operations for finitely generated abelian groups."""

from __future__ import annotations

from math import gcd, lcm

from jacobian.math.groups.abelian._models import (
    ElementEqualRequest,
    ElementEqualResult,
    ElementOrderRequest,
    ElementOrderResult,
    ElementReduceRequest,
    ElementReduceResult,
    PresentationNormalizeRequest,
    PresentationNormalizeResult,
    QuotientRequest,
    QuotientResult,
    SubgroupGeneratedRequest,
    SubgroupGeneratedResult,
)


def compute_presentation_normalize(
    request: PresentationNormalizeRequest,
) -> PresentationNormalizeResult:
    from sympy import Matrix, diag
    from sympy.matrices.normalforms import smith_normal_form

    matrix = Matrix(diag(*request.invariant_factors))
    smith = smith_normal_form(matrix, domain=None)
    factors = tuple(int(smith[i, i]) for i in range(min(smith.rows, smith.cols)))
    cleaned = tuple(factor for factor in factors if factor > 1)
    order = 1
    for factor in cleaned:
        order *= factor
    return PresentationNormalizeResult(
        invariant_factors=cleaned,
        order=order,
        rank=0,
    )


def compute_element_reduce(request: ElementReduceRequest) -> ElementReduceResult:
    reduced = tuple(
        coordinate % factor
        for coordinate, factor in zip(
            request.coordinates, request.invariant_factors, strict=True
        )
    )
    return ElementReduceResult(reduced=reduced)


def compute_element_equal(request: ElementEqualRequest) -> ElementEqualResult:
    reduced_a = tuple(
        coordinate % factor
        for coordinate, factor in zip(
            request.coordinates_a, request.invariant_factors, strict=True
        )
    )
    reduced_b = tuple(
        coordinate % factor
        for coordinate, factor in zip(
            request.coordinates_b, request.invariant_factors, strict=True
        )
    )
    return ElementEqualResult(equal=reduced_a == reduced_b)


def compute_element_order(request: ElementOrderRequest) -> ElementOrderResult:
    reduced = [
        coordinate % factor
        for coordinate, factor in zip(
            request.coordinates, request.invariant_factors, strict=True
        )
    ]
    order = 1
    for coordinate, factor in zip(reduced, request.invariant_factors, strict=True):
        if coordinate != 0:
            order = lcm(order, factor // gcd(coordinate, factor))
    return ElementOrderResult(order=order)


def _smith_diagonal(augmented_rows: list[list[int]]) -> list[int]:
    """Compute diagonal entries of the exact integer Smith normal form."""
    from sympy import Matrix
    from sympy.matrices.normalforms import smith_normal_form

    smith = smith_normal_form(Matrix(augmented_rows), domain=None)
    return [abs(int(smith[i, i])) for i in range(min(smith.rows, smith.cols))]


def compute_subgroup_generated(
    request: SubgroupGeneratedRequest,
) -> SubgroupGeneratedResult:
    """Compute the index of a subgroup generated by given elements."""
    factors = request.invariant_factors
    rows = [[0] * len(factors) for _ in factors]
    for index, factor in enumerate(factors):
        rows[index][index] = factor
    for generator in request.generators:
        for index, coordinate in enumerate(generator):
            rows[index].append(coordinate)
    diagonal = _smith_diagonal(rows)
    index = 1
    for factor in diagonal:
        if factor > 1:
            index *= factor
    return SubgroupGeneratedResult(index=index)


def compute_quotient(request: QuotientRequest) -> QuotientResult:
    """Compute the quotient group via Smith normal form."""
    factors = request.invariant_factors
    rows = [[0] * len(factors) for _ in factors]
    for index, factor in enumerate(factors):
        rows[index][index] = factor
    for generator in request.subgroup_generators:
        for index, coordinate in enumerate(generator):
            rows[index].append(coordinate)
    diagonal = _smith_diagonal(rows)
    quotient_factors = tuple(factor for factor in diagonal if factor > 1)
    order = 1
    for factor in quotient_factors:
        order *= factor
    return QuotientResult(
        quotient_invariant_factors=quotient_factors,
        quotient_order=order,
    )


