class BurnsideCountRequest(_ActionRequest):
    """Request the number of orbits under the action via Burnside's lemma."""


class BurnsideCountResult(StrictModel):
    """Source-bound Burnside point-orbit count under the action.

    ``orbit_count`` is the exact integer ``|G\\X| = (1/|G|) sum_g |Fix(g)|``.
    ``fixed_point_contributions`` lists, for each group element, its
    ``|Fix(g)|`` value in enumerated order.  ``group_order`` is ``|G|``.  The
    fixed-point sum and quotient are claims established by the producing
    operation and checked by ``verify_burnside_count`` when a consumer relies
    on them.
    """

    action: FinitePermutationAction
    group_order: int
    fixed_point_sum: int = Field(ge=0, le=MAX_GROUP_ORDER * MAX_DOMAIN_SIZE)
    orbit_count: int = Field(ge=0, le=MAX_DOMAIN_SIZE)
    fixed_point_contributions: tuple[int, ...] = Field(max_length=MAX_GROUP_ORDER)

    @model_validator(mode="after")
    def bind_burnside(self) -> Self:
        if not 1 <= self.group_order <= MAX_GROUP_ORDER:
            raise _validation_error(
                "group_order_exceeds_bound",
                "group_order must stay within the group-order bound",
            )
        if len(self.fixed_point_contributions) != self.group_order or any(
            contribution < 0 or contribution > len(self.action.domain)
            for contribution in self.fixed_point_contributions
        ):
            raise _validation_error(
                "fixed_point_contributions_invalid",
                "fixed-point contributions must be bounded and one per group element",
            )
        return self

    @classmethod
    def _from_kernel(
        cls,
        action: FinitePermutationAction,
        group_order: int,
        fixed_point_contributions: tuple[int, ...],
        orbit_count: int,
    ) -> Self:
        return cls.model_construct(
            action=action,
            group_order=group_order,
            fixed_point_sum=sum(fixed_point_contributions),
            orbit_count=orbit_count,
            fixed_point_contributions=fixed_point_contributions,
        )


