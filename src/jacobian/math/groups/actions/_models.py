class PolyaInventoryRequest(_ActionRequest):
    """Request the Pólya enumeration inventory polynomial.

    ``colors`` is the number of colours ``k``.  The inventory polynomial counts
    colouring orbits of ``X`` by colour multiplicity.  Its monomials are
    ``k``-tuples ``(e_1, ..., e_k)`` summing to ``|X|`` and its coefficients
    count orbits of colourings with exactly ``e_c`` points of colour ``c``.
    """

    colors: int = Field(ge=1, le=MAX_COLORS)


class PolyaInventoryResult(StrictModel):
    """Source-bound Pólya enumeration inventory polynomial as sparse data.

    ``terms`` maps each monomial exponent tuple (a ``k``-tuple of non-negative
    integers summing to ``degree``) to its integer coefficient.  ``colors`` is
    the number of colours and ``degree`` is ``|X|``.  The coefficient sum is
    ``k^|X| / |G| * |G| = k^|X|`` only when the action is trivial; in general
    the coefficients are the Pólya inventory coefficients.
    The degree and coefficient identities are established by the producing
    operation and checked by ``verify_polya_inventory`` when a consumer relies
    on this claim.  Deserialization checks only the bounded sparse shape.
    """

    action: FinitePermutationAction
    colors: int = Field(ge=1, le=MAX_COLORS)
    degree: int
    terms: tuple[tuple[tuple[int, ...], int], ...] = Field(max_length=MAX_TERMS)

    @model_validator(mode="after")
    def bind_polya(self) -> Self:
        if self.degree != len(self.action.domain):
            raise _validation_error("degree_mismatch", "degree must equal |X|")
        if len(self.terms) > MAX_TERMS or tuple(sorted(self.terms)) != self.terms:
            raise _validation_error(
                "terms_not_canonical", "terms must be a bounded sorted tuple"
            )
        if len({monomial for monomial, _ in self.terms}) != len(self.terms):
            raise _validation_error("terms_duplicate", "monomials must be unique")
        if any(
            len(monomial) != self.colors
            or any(exponent < 0 for exponent in monomial)
            or coefficient < 1
            for monomial, coefficient in self.terms
        ):
            raise _validation_error(
                "terms_invalid",
                "each term must be a positive coefficient on a degree monomial",
            )
        return self

    @classmethod
    def _from_kernel(
        cls,
        action: FinitePermutationAction,
        colors: int,
        degree: int,
        terms: tuple[tuple[tuple[int, ...], int], ...],
    ) -> Self:
        return cls.model_construct(
            action=action, colors=colors, degree=degree, terms=terms
        )
