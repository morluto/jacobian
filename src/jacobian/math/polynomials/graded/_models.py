MAX_GRADED_DEGREE = 32
MAX_STANDARD_MONOMIALS = 20_000
MAX_HILBERT_SERIES_GENERATORS = 8
MAX_HILBERT_PREFIX = 16

NonnegativeHilbertCount = Annotated[StrictInt, Field(ge=0)]
GradedMonomial = Annotated[
    tuple[StrictInt, ...],
    Field(max_length=MAX_POLYNOMIAL_VARIABLES),
]


class InitialMonomialIdealRequest(StrictModel):
    ideal: RationalPolynomialIdeal = Field(
        description=(
            "A homogeneous ideal over QQ whose generators share the source ring, "
            "so its Groebner basis and initial monomial ideal are well defined."
        )
    )
    monomial_order: Literal["lex", "grlex", "grevlex"] = "grevlex"
    resource_budget: IdealComputationBudget = Field(
        default_factory=IdealComputationBudget
    )


class InitialMonomialIdealResult(StrictModel):
    ideal: RationalPolynomialIdeal
    groebner_basis: RationalPolynomialIdeal
    initial_ideal: RationalPolynomialIdeal
    monomial_order: Literal["lex", "grlex", "grevlex"]

    @model_validator(mode="after")
    def require_same_ring(self) -> Self:
        if not (
            self.ideal.variables
            == self.groebner_basis.variables
            == self.initial_ideal.variables
        ):
            raise ValueError("initial-ideal values must share one ordered ring")
        for generator in self.initial_ideal.generators:
            terms = generator.polynomial.terms
            if not terms:
                continue
            if len(terms) != 1 or terms[0].coefficient != CanonicalRational(
                num=1, den=1
            ):
                raise ValueError(
                    "initial ideals must be generated by unit monomials or zero"
                )
        return self


class StandardMonomialsRequest(StrictModel):
    initial_ideal: RationalPolynomialIdeal = Field(
        description=(
            "A monomial ideal over QQ whose generators are unit monomials "
            "(coefficient one), the initial ideal of a graded quotient."
        )
    )
    degree: StrictInt = Field(ge=0, le=MAX_GRADED_DEGREE)


class StandardMonomialsResult(StrictModel):
    initial_ideal: RationalPolynomialIdeal
    degree: StrictInt = Field(ge=0, le=MAX_GRADED_DEGREE)
    monomials: tuple[GradedMonomial, ...] = Field(max_length=MAX_STANDARD_MONOMIALS)
    count: StrictInt = Field(ge=0, le=MAX_STANDARD_MONOMIALS)

    @model_validator(mode="after")
    def require_count(self) -> Self:
        if self.count != len(self.monomials):
            raise ValueError("standard-monomial count must match the returned list")
        if any(
            len(monomial) != len(self.initial_ideal.variables)
            or sum(monomial) != self.degree
            or any(exponent < 0 for exponent in monomial)
            for monomial in self.monomials
        ):
            raise ValueError(
                "standard monomials must match the ordered ring and degree"
            )
        if self.monomials != tuple(sorted(set(self.monomials), reverse=True)):
            raise ValueError("standard monomials must be unique and canonical")
        generators: list[tuple[int, ...]] = []
        for generator in self.initial_ideal.generators:
            terms = generator.polynomial.terms
            if not terms:
                continue
            if len(terms) != 1 or terms[0].coefficient != CanonicalRational(
                num=1, den=1
            ):
                raise ValueError(
                    "standard-monomial operations require unit monomial generators"
                )
            generators.append(terms[0].exponents)
        if any(
            any(
                len(generator) == len(monomial)
                and all(
                    left <= right
                    for left, right in zip(generator, monomial, strict=True)
                )
                for generator in generators
            )
            for monomial in self.monomials
        ):
            raise ValueError(
                "standard monomials must not be divisible by an initial-ideal generator"
            )
        return self


