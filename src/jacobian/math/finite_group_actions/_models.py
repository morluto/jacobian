class CycleIndexRequest(_ActionRequest):
    """Request the cycle-index polynomial of the action."""


class CycleIndexResult(StrictModel):
    """The cycle-index polynomial Z(G) as sparse coefficient data.

    ``cycle_type -> coefficient`` maps a cycle-type tuple (an integer partition
    of ``|X|`` given by cycle counts) to the number of group elements with
    that cycle type.  ``group_order`` is ``|G|`` and ``degree`` is ``|X|``.
    Each coefficient is exact; the cycle index is ``coeff / group_order``.
    """

    action: FinitePermutationAction
    group_order: int
    degree: int
    cycle_type_counts: tuple[tuple[tuple[int, ...], int], ...]

    @model_validator(mode="after")
    def bind_cycle_index(self) -> Self:
        from jacobian.math.finite_group_actions._operations import _cycle_index_data

        order, degree, counts = _cycle_index_data(self.action)
        if self.group_order != order:
            raise ValueError("group_order must equal the exact |G|")
        if self.degree != degree:
            raise ValueError("degree must equal |X|")
        if self.cycle_type_counts != counts:
            raise ValueError(
                "cycle_type_counts must be the exact cycle-type multiplicity table"
            )
        return self


