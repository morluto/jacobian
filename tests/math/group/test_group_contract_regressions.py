def test_group_conjugacy_classes_result_accepts_trivial_and_abelian_partitions() -> (
    None
):
    from jacobian.math.group._models import GroupConjugacyClassesResult

    trivial = GroupConjugacyClassesResult(
        degree=1,
        generators=((0,),),
        classes=({"elements": ((0,),), "size": 1},),
        class_count=1,
    )
    assert trivial.class_count == 1
    cyclic_c4 = GroupConjugacyClassesResult(
        degree=4,
        generators=((1, 2, 3, 0),),
        classes=tuple(
            {"elements": (cycle,), "size": 1}
            for cycle in [(0, 1, 2, 3), (1, 2, 3, 0), (2, 3, 0, 1), (3, 0, 1, 2)]
        ),
        class_count=4,
    )
    assert cyclic_c4.class_count == 4


def _mutated_s3_payload(mutation) -> dict:
    payload = _s3_result().model_dump(mode="json")
    mutation(payload)
    return payload


def test_group_conjugacy_classes_result_rejects_non_permutations() -> None:
    from jacobian.math.group._models import GroupConjugacyClassesResult

    def inject(payload):
        payload["classes"][0]["elements"] = [[0, 0]]

    with pytest.raises(ValidationError):
        GroupConjugacyClassesResult.model_validate(_mutated_s3_payload(inject))


def test_group_conjugacy_classes_result_rejects_duplicate_elements() -> None:
    from jacobian.math.group._models import GroupConjugacyClassesResult

    def duplicate(payload):
        payload["classes"][1]["elements"].append([0, 2, 1])
        payload["classes"][1]["size"] = len(payload["classes"][1]["elements"])

    with pytest.raises(ValidationError):
        GroupConjugacyClassesResult.model_validate(_mutated_s3_payload(duplicate))


def test_group_conjugacy_classes_result_rejects_wrong_partition_of_valid_group() -> (
    None
):
    """A valid group split into non-conjugacy classes must be rejected."""
    from jacobian.math.group._models import GroupConjugacyClassesResult

    def repartition(payload):
        payload["classes"] = [
            {"elements": [[0, 1, 2]], "size": 1},
            {"elements": [[0, 2, 1], [2, 1, 0]], "size": 2},
            {"elements": [[1, 0, 2]], "size": 1},
            {"elements": [[1, 2, 0], [2, 0, 1]], "size": 2},
        ]
        payload["class_count"] = 4

    with pytest.raises(ValidationError, match="conjugacy partition"):
        GroupConjugacyClassesResult.model_validate(_mutated_s3_payload(repartition))


def test_group_conjugacy_classes_result_requires_canonical_member_order() -> None:
    from jacobian.math.group._models import GroupConjugacyClassesResult

    def unsort_members(payload):
        transposition_class = next(
            entry
            for entry in payload["classes"]
            if {tuple(p) for p in entry["elements"]}
            == {(0, 2, 1), (1, 0, 2), (2, 1, 0)}
        )
        transposition_class["elements"] = list(
            reversed(transposition_class["elements"])
        )

    with pytest.raises(ValidationError, match="canonical element and class order"):
        GroupConjugacyClassesResult.model_validate(_mutated_s3_payload(unsort_members))


def test_group_conjugacy_classes_result_requires_representative_class_order() -> None:
    from jacobian.math.group._models import GroupConjugacyClassesResult

    def reorder_classes(payload):
        payload["classes"] = list(reversed(payload["classes"]))

    with pytest.raises(ValidationError, match="canonical element and class order"):
        GroupConjugacyClassesResult.model_validate(_mutated_s3_payload(reorder_classes))


def test_group_subgroup_lattice_result_requires_canonical_entry_order() -> None:
    from jacobian.math.group._models import (
        GroupSubgroupLatticeRequest,
        GroupSubgroupLatticeResult,
    )
    from jacobian.math.group._operations import compute_subgroup_lattice

    result = compute_subgroup_lattice(
        GroupSubgroupLatticeRequest(degree=4, generators=((1, 2, 3, 0),))
    )
    payload = result.model_dump(mode="json")
    payload["subgroups"] = list(reversed(payload["subgroups"]))
    with pytest.raises(ValidationError, match="canonical element and entry order"):
        GroupSubgroupLatticeResult.model_validate(payload)


def test_group_conjugacy_classes_result_round_trips_through_model_dump() -> None:
    from jacobian.math.group._models import GroupConjugacyClassesResult

    result = _s3_result()
    revived = GroupConjugacyClassesResult.model_validate(result.model_dump())
    assert revived == result
