from __future__ import annotations

import pytest
from pydantic import ValidationError

from jacobian.math.group._models import GroupOrbitRequest


def test_group_orbit_contract_binds_the_point_to_the_declared_degree() -> None:
    with pytest.raises(ValidationError, match="point"):
        GroupOrbitRequest(degree=2, generators=((1, 0),), point=3)


def _s3_request():
    from jacobian.math.group._models import GroupConjugacyClassesRequest

    return GroupConjugacyClassesRequest(
        degree=3,
        generators=((1, 2, 0), (1, 0, 2)),
    )


def _s3_result():
    from jacobian.math.group._operations import compute_conjugacy_classes

    return compute_conjugacy_classes(_s3_request())


def test_group_conjugacy_classes_partition_s3() -> None:
    """S3 has three conjugacy classes of sizes 1, 2, 3."""
    result = _s3_result()
    assert result.class_count == 3
    sizes = sorted(cls.size for cls in result.classes)
    assert sizes == [1, 2, 3]
    # classes partition the group: total elements == |S3| = 6
    assert sum(cls.size for cls in result.classes) == 6
    # the identity (0,1,2) is its own class
    identity_class = [cls for cls in result.classes if cls.elements == ((0, 1, 2),)]
    assert len(identity_class) == 1
    assert identity_class[0].size == 1


def test_group_conjugacy_classes_abelian_group_is_singletons() -> None:
    """In an abelian group every element is its own conjugacy class."""
    from jacobian.math.group._models import GroupConjugacyClassesRequest
    from jacobian.math.group._operations import (
        compute_conjugacy_classes,
        compute_group_order,
    )

    # Cyclic group C3 generated by the 3-cycle (1,2,0).
    gens = ((1, 2, 0),)
    request = GroupConjugacyClassesRequest(degree=3, generators=gens)
    result = compute_conjugacy_classes(request)
    order = int(compute_group_order(request).order)
    assert order == 3
    assert result.class_count == 3
    for cls in result.classes:
        assert cls.size == 1


def test_group_conjugacy_classes_canonical_order_s3() -> None:
    """Members are lexicographically sorted; classes sort by first element."""
    result = _s3_result()
    assert tuple(cls.elements for cls in result.classes) == (
        ((0, 1, 2),),
        ((0, 2, 1), (1, 0, 2), (2, 1, 0)),
        ((1, 2, 0), (2, 0, 1)),
    )


def test_group_conjugacy_classes_serialization_is_hash_seed_independent() -> None:
    """Separate processes serialize the same partition identically."""
    import os
    import subprocess
    import sys

    script = (
        "from jacobian.math.group.operations import conjugacy_classes;"
        "import json;"
        "print(json.dumps(conjugacy_classes(3, [[1, 2, 0], [1, 0, 2]])))"
    )
    outputs = set()
    for seed in ("0", "1", "424242"):
        env = dict(os.environ)
        env["PYTHONHASHSEED"] = seed
        proc = subprocess.run(
            [sys.executable, "-c", script],
            capture_output=True,
            text=True,
            env=env,
            check=True,
        )
        outputs.add(proc.stdout.strip())
    assert len(outputs) == 1


